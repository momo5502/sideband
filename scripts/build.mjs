import { rm, readFile, readdir, writeFile } from "node:fs/promises";
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";
import { spawnSync } from "node:child_process";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const output = join(root, "dist");
if (relative(root, output) !== "dist") throw new Error("Unsafe build output path.");
// Only the explicitly named generated build directory is removed, never workspace/source state.
await rm(output, { recursive: true, force: true });
const css = spawnSync(process.execPath, [join(root, "node_modules/@tailwindcss/cli/dist/index.mjs"), "-i", "src/browser.css", "-o", "dist/browser.css", "--minify"], { cwd: root, stdio: "inherit", windowsHide: true });
if (css.error) throw css.error;
if (css.status !== 0) process.exit(css.status ?? 1);
// Browser signing works on HTTP too: pure-JS Ed25519/SHA-256, with getRandomValues entropy.
// Embed the complete browser app so the standalone runtime needs no separate assets or CDN.
const browser = await build({ absWorkingDir: root, entryPoints: ["src/browser-ui.ts"], bundle: true,
  platform: "browser", format: "iife", target: "es2022", jsx: "automatic", define: { "process.env.NODE_ENV": '"production"' }, minify: true, write: false, legalComments: "eof", metafile: true });
async function packageNotices(metafiles) {
  const packages = new Set([join(root, "node_modules/tailwindcss")]);
  for (const input of new Set(metafiles.flatMap(meta => Object.keys(meta.inputs)))) {
    if (!input.includes("node_modules/")) continue;
    let directory = dirname(join(root, input));
    while (directory !== root && relative(root, directory) && !relative(root, directory).startsWith("..")) {
      try {
        const manifest = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
        if (manifest.name && manifest.version) { packages.add(directory); break; }
      } catch { /* Module-format subdirectories aren't package roots. */ }
      directory = dirname(directory);
    }
  }
  const notices = [];
  for (const directory of [...packages].sort()) {
    const manifest = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
    const licenses = (await readdir(directory)).filter(name => /^(licen[cs]e|copying|notice)(\.|$)/i.test(name));
    if (!licenses.length) {
      if (manifest.name === "react-remove-scroll-bar" && manifest.version === "2.3.8") {
        notices.push(`${manifest.name}@${manifest.version} — LICENSE\n${await readFile(join(root, "scripts/licenses/react-remove-scroll-bar.LICENSE"), "utf8")}`);
        continue;
      }
      if ((manifest.name === "agent-base" && manifest.version === "6.0.2") || (manifest.name === "https-proxy-agent" && manifest.version === "5.0.1")) {
        // This version publishes its complete MIT license in README.md, but no LICENSE file.
        const readme = await readFile(join(directory, "README.md"), "utf8");
        const license = /\(The MIT License\)[\s\S]*?SOFTWARE\./.exec(readme)?.[0];
        if (!license) throw new Error(`Missing ${manifest.name} README license.`);
        notices.push(`${manifest.name}@${manifest.version} — README license\n${license.replace(/&lt;/g, "<").replace(/&gt;/g, ">")}`);
        continue;
      }
      throw new Error(`Missing bundled license for ${manifest.name}.`);
    }
    for (const name of licenses.sort()) notices.push(`${manifest.name}@${manifest.version} — ${name}\n${await readFile(join(directory, name), "utf8")}`);
  }
  return notices;
}
const browserNotices = await packageNotices([browser.metafile]);
// Browser visitors also receive the libraries' copyright/license notices, not just npm installers.
// Radix's embedded CSS literals contain whitespace-only lines; normalize those in generated assets.
const browserSource = `${browser.outputFiles[0].text.replace(/^[ \t]+$/gm, "")}\n/*\n${browserNotices.join("\n\n").replace(/\*\//g, "* /").replace(/\r\n/g, "\n")}\n*/\n`;
const browserStyles = (await readFile(join(output, "browser.css"), "utf8")).replace(/<\/style/gi, "<\\/style");
await writeFile(join(root, "src/browser-bundle.ts"), `// Generated by scripts/build.mjs. Do not edit the bundle directly.\nexport const browserScript = ${JSON.stringify(browserSource)};\nexport const browserStyles = ${JSON.stringify(browserStyles)};\n`);
const result = spawnSync(process.execPath, [join(root, "node_modules/typescript/bin/tsc"), "-p", join(root, "tsconfig.json")], { stdio: "inherit", cwd: root, windowsHide: true });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);
// A Git-installed harness plugin cannot depend on npm install/prepare being run.
// Bundle all runtime dependencies; optional ws native accelerators stay disabled.
const bundled = await build({ absWorkingDir: root, entryPoints: ["src/cli.ts"], outfile: "dist/sideband.cjs",
  bundle: true, platform: "node", format: "cjs", target: "node22", minify: true,
  legalComments: "none", metafile: true, define: { "process.env.WS_NO_BUFFER_UTIL": '"1"', "process.env.WS_NO_UTF_8_VALIDATE": '"1"' } });
const omp = await build({ absWorkingDir: root, entryPoints: ["src/omp-extension.ts"], outfile: "dist/sideband-omp.cjs",
  bundle: true, platform: "node", format: "cjs", target: "node22", minify: true,
  footer: { js: "module.exports = module.exports.default;" },
  legalComments: "none", metafile: true, define: { "process.env.WS_NO_BUFFER_UTIL": '"1"', "process.env.WS_NO_UTF_8_VALIDATE": '"1"' } });
const pi = await build({ absWorkingDir: root, entryPoints: ["src/pi-extension.ts"], outfile: "dist/sideband-pi.cjs",
  bundle: true, external: ["typebox"], platform: "node", format: "cjs", target: "node22", minify: true,
  footer: { js: "module.exports = module.exports.default;" }, legalComments: "none", metafile: true,
  define: { "process.env.WS_NO_BUFFER_UTIL": '"1"', "process.env.WS_NO_UTF_8_VALIDATE": '"1"' } });
// Preserve third-party license files for dependencies included in the standalone runtime.
const notices = await packageNotices([bundled.metafile, omp.metafile, pi.metafile, browser.metafile]);
await writeFile(join(output, "THIRD_PARTY_NOTICES.txt"), notices.join("\n\n---\n\n").replace(/\r\n/g, "\n").replace(/[ \t]+$/gm, ""));
